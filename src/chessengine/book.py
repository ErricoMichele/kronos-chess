"""A tiny, self-contained opening book: a hash-keyed table of preferred
replies plus a single lookup function (architecture.md §15, Milestone 5).

Per the module-boundary DAG (architecture.md §11), `book.py` sits at the
same layer as `search.py`/`uci.py`: it depends on `board.py` and
`movegen.py` (to decode a UCI move string into this engine's own packed
move encoding via `movegen.move_from_uci`), and nothing below those two in
the DAG ever imports `book.py`, so this creates no cycle. `book.py` does
not import `search.py` and `search.py` does not import `book.py` — the
book is consulted only *before* the main search runs (by whatever caller,
e.g. the UCI layer, chooses to consult it) and has zero effect on
`Search.search`'s contract, exactly as §15 specifies.

**Format.** `OPENING_BOOK` is keyed by a position's Zobrist hash
(architecture.md §7 — the very same incrementally-maintained
`board.zobrist_hash`, not a separately-computed key) and maps to a list of
`(uci_move, weight)` pairs for that position: higher `weight` is more
preferred, and ties are broken by list order (first-listed wins), so
`probe_book` is fully deterministic and reproducible/testable.

**How the table below was produced.** Every key in `OPENING_BOOK` is the
*actual* `board.zobrist_hash` this engine computes for that position — not
a hand-computed or transcribed value. It was generated by a one-off script
that built a real `Board` via `Board.starting_position()`, replayed each
opening line's moves with `movegen.move_from_uci` + `board.make_move`, and
read `board.zobrist_hash` at every branching position, then printed the
resulting dict literal pasted in below. Since `zobrist.py` seeds its RNG
with a fixed constant (`random.Random(0xC0FFEE)`, see zobrist.py), these
keys are stable across runs/processes for this codebase, exactly like the
`board.zobrist_hash == compute_hash(board)` invariant `test_zobrist.py`
already relies on. The generation script (kept out of the package,
reproduced here for anyone who wants to regenerate or extend the table):

    import sys
    sys.path.insert(0, "src")
    from chessengine.board import Board
    from chessengine.movegen import move_from_uci

    # TREE: uci_move -> (weight, label, child_tree_or_None)
    TREE = { ... }  # the repertoire, see below for the one actually used

    entries = {}

    def walk(board, tree, path):
        entries[board.zobrist_hash] = [
            (uci, weight) for uci, (weight, _label, _child) in tree.items()
        ]
        for uci, (_weight, _label, child) in tree.items():
            m = move_from_uci(board, uci)
            board.make_move(m)
            if child:
                walk(board, child, path + [uci])
            board.unmake_move()

    root = Board.starting_position()
    walk(root, TREE, [])

**Repertoire covered** (a demonstration book, not a database): after 1.e4 —
...e5 (Ruy Lopez / Italian / Petrov branches), ...c5 (Sicilian: Najdorf /
Open / Rossolimo), ...e6 (French: Classical / Tarrasch), ...c6 (Caro-Kann:
Classical / Advance); after 1.d4 — ...d5 (Queen's Gambit: QGD / Slav /
QGA), ...Nf6 (Indian: King's Indian / Nimzo-QID setups); plus 1.Nf3 (Reti)
and 1.c4 (English) as alternate first moves, each with a short reply tree.
"""


def probe_book(board: Board) -> int | None:
    """Look up `board`'s current position in `OPENING_BOOK` and return the
    engine's own encoded move (architecture.md §4) for the single
    highest-weight entry, or `None` if the position isn't in the book.

    Deterministic: ties are broken by first-listed entry (§15), so this is
    reproducible/testable without relying on dict ordering guarantees beyond
    what `OPENING_BOOK`'s own list order already provides. Decodes via
    `movegen.move_from_uci` against the *current* legal move list, so it can
    never hand back a move the position's own generator wouldn't produce —
    the same safety property `move_from_uci` gives UCI's `position ... moves
    ...` handling.

    Standalone: never imports or calls anything in `search.py`, and nothing
    in `search.py` calls this — consulting it (or not) before `Search.search`
    runs is entirely up to the caller (the UCI layer, in a later phase).
    """
    moves = OPENING_BOOK.get(board.zobrist_hash)
    if not moves:
        return None
    best_uci, _best_weight = max(
        enumerate(moves), key=lambda pair: (pair[1][1], -pair[0])
    )[1]
    return move_from_uci(board, best_uci)
